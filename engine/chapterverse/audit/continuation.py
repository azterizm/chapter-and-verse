SAMPLING: Final[Mapping[ChatMode, tuple[float, float]]] = {
    "short": (0.7, 0.8),
    "synthesis": (1.0, 0.95),
}
"""(temperature, top_p) per request mode: Qwen's non-thinking and thinking cards (decision 6)."""

SENTENCE_TOO_LONG: Final = "SENTENCE_TOO_LONG"
EMPTY_BLOCK: Final = "EMPTY_BLOCK"

StopReason = Literal["stop", "length", "rollback_budget", "block_limit", "content_filter", "other"]

_PARTIAL_REF = re.compile(r"\s*\[[^\]\n]*\Z")
_TERMINAL = ".;:"


@dataclass(frozen=True, slots=True, kw_only=True)
class GenerationSettings:
    """Request shape and answer bounds. ``max_answer_tokens`` None: 512 short, 1536 synthesis."""

    block_tokens: int = 200
    max_answer_tokens: int | None = None
    max_blocks: int = 32
    seed: int | None = 0
    thinking_tokens: int = 2048
    inject_windows: int = 2
    inject_max_chars: int = 3200

    def answer_limit(self, mode: ChatMode) -> int:
        if self.max_answer_tokens is not None:
            return self.max_answer_tokens
        return 512 if mode == "short" else 1536


def _move_refs(body: str, refs: str) -> str:
    """Move references written after the stop before it: ``"£5. [P1]"`` -> ``"£5 [P1]."``."""
    if body and body[-1] in _TERMINAL:
        return f"{body[:-1].rstrip()} {refs}{body[-1]}"
    return f"{body} {refs}"


def split_block(text: str, *, final: bool) -> tuple[list[str], bool]:
    """The complete sentences of a block, with their references, and whether nothing is left.

    ``final`` is True when the model stopped by itself: then the text after the last stop is a
    sentence too. Otherwise a trailing sentence the segmenter cannot yet confirm (or one whose
    reference is cut off) is left out and the second value is False.
    """
    sentences: list[str] = []
    pos = 0
    lead = REF_GROUPS.match(text)
    if lead is not None:
        pos = lead.end()  # references back to a sentence already committed
    while True:
        if not text[pos:].strip():
            return sentences, True
        end = find_boundary(text, pos, final=final)
        if end is None:
            return sentences, False
        refs = REF_GROUPS.match(text, end)
        if refs is None and not final and _PARTIAL_REF.match(text, end):
            return sentences, False
        body = text[pos:end].strip()
        if refs is not None:
            body = _move_refs(body, text[end : refs.end()].strip()) if body else ""
            end = refs.end()
        if body:
            sentences.append(body)
        pos = end


@dataclass
class _State:
    """One answer in progress."""

    context: str = ""
    index: int = 0
    point: int = 0  # discarded drafts at the current point
    total: int = 0  # discarded drafts in the answer
    blocks: int = 0
    seed_offset: int = 0
    answer_chars: int = 0
    noted: bool = False
    injected: set[int] = field(default_factory=set)
    last_reasons: tuple[str, ...] = ()

    def commit(self, text: str) -> None:
        sep = " " if self.context and not self.context[-1].isspace() else ""
        self.context += sep + text


class ChatContinuationGenerator:
    """Iterate to get each audited :class:`SentenceOut` as soon as it is decided.

    One instance answers one question, once. ``calls`` holds every successful generation and judge
    call in order; ``stop_reason`` is set when the iteration ends normally.
    """

    def __init__(
        self,
        rotation: Rotation,
        judge_chat: JudgeChat,
        policy: Policy,
        *,
        query: str,
        premise: Premise,
        windows: Sequence[Window],
        mode: ChatMode = "short",
        session: SessionState | None = None,
        history: Sequence[PriorTurn] = (),
        settings: GenerationSettings | None = None,
    ) -> None:
        self.rotation = rotation
        self.judge_chat = judge_chat
        self.policy = policy
        self.query = query
        self.premise = premise
        self.settings = settings or GenerationSettings()
        self.prompt: Prompt = build_prompt(
            query, windows, mode=mode, session=session, history=history
        )
        self.positions = window_positions(premise, windows)
        self.calls: list[ProviderCall] = []
        self.stop_reason: StopReason | None = None
        self._started = False

    def __iter__(self) -> Iterator[SentenceOut]:
        if self._started:
            raise RuntimeError("a ChatContinuationGenerator answers once")
        self._started = True
        return self._run()

    # ------------------------------------------------------------------ the loop
    def _run(self) -> Iterator[SentenceOut]:
        verifier = make_verifier(self.judge_chat, self.policy, self.prompt.passage_ids, self.calls)
        state = _State()
        limit = self.settings.answer_limit(self.prompt.mode)
        while True:
            if state.blocks >= self.settings.max_blocks:
                self.stop_reason = "block_limit"
                return
            result = self._request(state)
            sentences, _ = split_block(result.text, final=result.finish_reason == "stop")
            rejected: SentenceVerdict | None = None
            for raw in sentences:
                verdict = verifier.check_sentence(self.premise, raw, query=self.query)
                if not verdict.emitted:
                    rejected = verdict
                    break
                state.commit(raw)
                state.answer_chars += len(verdict.text) + 1
                yield self._emitted(state, raw, verdict)
                if state.answer_chars / CHARS_PER_TOKEN >= limit:
                    self.stop_reason = "length"
                    return
            refusal = self._after_block(state, result, sentences, rejected)
            if refusal is not None:
                yield refusal
            if self.stop_reason is not None:
                return

    def _after_block(
        self,
        state: _State,
        result: ChatResult,
        sentences: Sequence[str],
        rejected: SentenceVerdict | None,
    ) -> SentenceOut | None:
        """Decide what a block that emitted no further sentence means. Sets ``stop_reason``
        when the answer ends; returns a refusal sentence to stream, if one was committed."""
        if rejected is not None:
            reasons = reason_codes(rejected.reasons, rejected.details)
            return self._rollback(state, reasons, rejected.aligned)
        if not sentences and result.finish_reason == "length":
            reasons = (EMPTY_BLOCK if not result.text.strip() else SENTENCE_TOO_LONG,)
            return self._rollback(state, reasons, ())
        if result.finish_reason == "stop":
            self.stop_reason = "stop"
            # A retry that gave nothing: say so (the engine's rule).
            return self._refuse(state) if not sentences and state.point else None
        if result.finish_reason in ("content_filter", "other"):
            self.stop_reason = result.finish_reason
        return None  # cut by the token limit after complete sentences: next block

    def _request(self, state: _State) -> ChatResult:
        thinking = self.prompt.mode == "synthesis" and state.blocks == 0
        mode: ChatMode = "synthesis" if thinking else "short"
        temperature, top_p = SAMPLING[mode]
        seed = self.settings.seed
        request = ChatRequest(
            messages=self.prompt.messages,
            max_tokens=self.settings.block_tokens
            + (self.settings.thinking_tokens if thinking else 0),
            temperature=temperature,
            top_p=top_p,
            mode=mode,
            prefill=state.context or None,
            seed=None if seed is None else seed + state.seed_offset,
            purpose="generate",
        )
        result = self.rotation.complete(request)
        state.blocks += 1
        self.calls.append(ProviderCall.from_result(result, "generate"))
        return result

    # ------------------------------------------------------------------ decisions
    def _emitted(self, state: _State, raw: str, verdict: SentenceVerdict) -> SentenceOut:
        out = SentenceOut(
            index=state.index,
            text=verdict.text,
            verdict="supported",
            passage_ids=split_refs(raw)[1],
            reasons=reason_codes(verdict.reasons, verdict.details),
            rollbacks=state.point,
        )
        state.index += 1
        state.point = 0
        return out

    def _refuse(self, state: _State) -> SentenceOut:
        refusal = self.policy.refusal_text
        state.commit(refusal)
        state.answer_chars += len(refusal) + 1
        out = SentenceOut(
            index=state.index,
            text=refusal,
            verdict="refused",
            passage_ids=(),
            reasons=state.last_reasons,
            rollbacks=state.point,
        )
        state.index += 1
        state.point = 0
        return out

    def _rollback(
        self, state: _State, reasons: tuple[str, ...], aligned: Sequence[int]
    ) -> SentenceOut | None:
        """Count a discarded draft; refuse when a budget is spent, else steer the retry."""
        state.point += 1
        state.total += 1
        state.last_reasons = reasons
        policy = self.policy
        if (
            state.point > policy.max_rollbacks_per_sentence
            or state.total > policy.max_total_rollbacks
        ):
            refusal = self._refuse(state)
            if state.total > policy.max_total_rollbacks:
                self.stop_reason = "rollback_budget"
            return refusal
        self._steer(state, reasons, aligned)
        return None

    def _steer(self, state: _State, reasons: tuple[str, ...], aligned: Sequence[int]) -> None:
        if any(r in REF_CODES for r in reasons) and not state.noted:
            state.noted = True
            state.context += STEER_NOTE
            return
        if self.policy.steering == "inject":
            fresh = [i for i in dict.fromkeys(aligned) if i in self.positions]
            fresh = [i for i in fresh if i not in state.injected][: self.settings.inject_windows]
            if fresh:
                state.injected.update(fresh)
                source = render_source([self.positions[i] for i in fresh])
                cap = self.settings.inject_max_chars
                if len(source) > cap:
                    source = source[:cap].rstrip() + f" {ELLIPSIS}"
                state.context += INJECT_TEMPLATE.format(source=source, query=self.query)
                return
        state.seed_offset += 1
