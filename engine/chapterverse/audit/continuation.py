"""Verified generation on hosted chat APIs (Groq, Cloudflare): the Strict Auditor's Pattern 1.

Hosted APIs expose no KV cache, so rollback works on text (plan §7, "KV truncation"). The
assistant turn the model continues (``ChatRequest.prefill``) is the *context*: every committed
sentence, refusal and injected source so far. Each request asks for a block of up to
``block_tokens`` (200) tokens after it. The block is split with the verifier's segmenter and its
complete sentences are verified in order by a per-answer :class:`~.verify.AuditVerifier` (the
judge on ``judge_chat``). Each sentence the verifier emits is committed to the context and
yielded at once. At the first rollback, that sentence and the rest of the block are discarded and
the policy decides; the next block starts from the context again.

Prefill rule. A sentence is committed only when the segmenter confirms its end, so the context
always ends at a sentence end (or after an injected source, which ends in a blank line). A trailing
incomplete sentence is dropped and regenerated by the next block: Groq breaks on a prefix that ends
mid-word (docs/decisions/0001-providers.md, decision 7). References the model writes after the
full stop (``"... £5. [P1]"``) stay with their sentence and are moved before the stop
(``"... £5 [P1]."``); references at the very start of a block, which point back at a committed
sentence, are dropped.

Policy (``contracts.Policy``), with the semantics of the verifier's ``InFlightGenerator``:

* a point is retried at most ``max_rollbacks_per_sentence`` (3) times; the 4th discarded draft
  commits ``refusal_text`` and the answer moves on (that sentence shows ``rollbacks == 4``);
* past ``max_total_rollbacks`` (8) discarded drafts in the answer, the refusal ends the answer;
* a retry that produces nothing (the model stops) commits the refusal.

Steering after a rollback, emulated in text:

* ``inject``: the windows the verifier aligned the rejected sentence to (at most 2, each once per
  answer, as passage ids the prompt knows) are written into the context with the verifier's
  ``INJECT_TEMPLATE`` (``SOURCE_TEMPLATE`` per window, full window text, cut at
  ``inject_max_chars``), and the point is regenerated from its start. The source stays in the
  context, never in the answer;
* a sentence that failed the passage-reference rules gets ``STEER_NOTE`` written into the context
  instead, once per answer;
* otherwise (no new window, or ``ban``/``allow`` steering, which need logit control the hosted APIs
  do not give) the point is resampled: the request seed moves on by one.

Blocks that hold no complete sentence (``SENTENCE_TOO_LONG``) or no text (``EMPTY_BLOCK``) while
cut by the token limit count as discarded drafts too, so every loop is bounded by the budget.

Stop reasons (``stop_reason``): ``stop`` (the model finished and every sentence was decided),
``length`` (the committed answer reached ``max_answer_tokens``, estimated), ``rollback_budget``,
``block_limit`` (``max_blocks`` requests), ``content_filter`` or ``other`` (the provider's finish
reason; the verified sentences before it stand).

Synthesis mode: thinking is requested (``mode="synthesis"``, ``thinking_tokens`` more tokens) for
the answer's first block only; later blocks continue the verified text with thinking off, because
every block resends the prompt and a thinking pass per block would not fit Groq's free tier.

``AllProvidersUnavailable`` from the rotation or the judge propagates unchanged, also after
sentences were yielded; the pipeline then closes the answer (docs/ARCHITECTURE.md §5).
"""

